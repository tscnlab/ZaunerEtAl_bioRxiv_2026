options(stringsAsFactors = FALSE)
stopifnot(getRversion() == "4.6.1")
root <- normalizePath(getwd(), mustWork = TRUE)
out <- file.path(root, "audit/manuscript_nature_health/revision_2026_09_11/consolidated_display_repair_order72k")
sel <- file.path(root, "audit/manuscript_nature_health/consolidated_display_repair_2026_09_11/integration_candidate_order72k")
record <- file.path(out, "correction_preflight")
stopifnot(!dir.exists(record))
dir.create(record)
sha <- function(p) { con <- file(p, "rb"); on.exit(close(con)); unname(unclass(as.character(openssl::sha256(con)))) }
baseline <- read.csv(file.path(out, "input_identity_before.csv"), check.names = FALSE)
paths <- ifelse(startsWith(baseline$path, "/"), baseline$path, file.path(root, baseline$path))
baseline$correction_sha256 <- vapply(paths, sha, character(1))
baseline$correction_bytes <- file.info(paths)$size
baseline$correction_exact <- baseline$correction_sha256 == baseline$expected_sha256 & baseline$correction_bytes == baseline$bytes
write.csv(baseline, file.path(record, "original_429_identities.csv"), row.names = FALSE)
stopifnot(all(baseline$correction_exact))
pins_path <- file.path(root, "audit/report_harmonization/report018_order72k_non_s5_integration_dispatch/lua_dependency_closure_pins.csv")
stopifnot(sha(pins_path) == "62f27bb24c52d362cfd0b800c25208158bc92bc6772bae896d2f25e6179e3ef5")
pins <- read.csv(pins_path, check.names = FALSE)
pins$source <- file.path(root, pins$path)
pins$copy <- file.path(out, "project/resources", basename(pins$path))
stopifnot(nrow(pins) == 3L, !any(file.exists(pins$copy)), all(Sys.readlink(pins$source) == ""))
pins$source_sha256 <- vapply(pins$source, sha, character(1))
stopifnot(all(pins$source_sha256 == pins$sha256), all(file.info(pins$source)$size == pins$bytes))
stopifnot(all(file.copy(pins$source, pins$copy, overwrite = FALSE, copy.date = TRUE)))
pins$copy_sha256 <- vapply(pins$copy, sha, character(1))
stopifnot(all(pins$copy_sha256 == pins$sha256))
write.csv(pins, file.path(record, "lua_dependency_copies.csv"), row.names = FALSE)
snapshots <- data.frame(source = c(file.path(out, "project/order72k_layout.css"), file.path(sel, "project/order72k_layout.css"), file.path(out, "helpers/capture_word_tables.mjs")), name = c("main_layout_before.css", "selection_layout_before.css", "capture_word_tables_before.mjs"))
snapshots$copy <- file.path(record, snapshots$name)
stopifnot(all(file.copy(snapshots$source, snapshots$copy, overwrite = FALSE)))
snapshots$sha256 <- vapply(snapshots$source, sha, character(1))
stopifnot(all(vapply(snapshots$copy, sha, character(1)) == snapshots$sha256))
write.csv(snapshots, file.path(record, "correction_source_snapshots.csv"), row.names = FALSE)
writeLines(c("Layout/dependency identity checks only; no model or scientific computation.", capture.output(sessionInfo())), file.path(record, "session.txt"))
